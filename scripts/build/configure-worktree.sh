#!/usr/bin/env bash
# Install local Cargo defaults in each Linux seat checkout; never overwrite existing config.
set -euo pipefail
usage() {
    cat <<'HELP'
Usage: configure-worktree.sh [--refresh]
Install local Cargo defaults; --refresh replaces unchanged generated defaults.
To relocate an idle lane across filesystems, move its directory with mv, run
git -C <main-checkout> worktree repair <new-path>, then run this script with
--refresh from <new-path>. git worktree move supports the same filesystem only.
Customized Cargo configs require manual updates.
HELP
}
if [[ $# == 1 && $1 == --help ]]; then usage; exit 0; fi
[[ $# == 0 || ( $# == 1 && $1 == --refresh ) ]] || { usage >&2; exit 2; }
root=$(git rev-parse --show-toplevel)
script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
# Installer selects the ordinary default even if a parent shell exported an old target.
unset CARGO_TARGET_DIR
source "$script_dir/../build-cache.sh"
python3 - "$root" "${1:-}" "$script_dir" <<'PY'
import json
import shutil
import hashlib
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import tomllib
sys.path.insert(0, sys.argv[3])
import tmp_scratch
root = Path(sys.argv[1])
config = root / '.cargo/config.toml'
quote = json.dumps
header = '# Local SE Code build defaults. Generated by configure-worktree.sh.\n[build]\n'
target = f'target-dir = {quote(os.environ["CARGO_TARGET_DIR"])}\n'
jobs = f'jobs = {int(os.environ["CARGO_BUILD_JOBS"])}\n'
flags = f'rustflags = {quote(os.environ["RUSTFLAGS"].split())}\n\n[env]\n'
cache = ''.join(f'{name} = {{ value = {quote(os.environ[name])}, force = false }}\n' for name in ['SECODE_CACHE_DIR', 'SECODE_FIXTURES'])
# The managed-root claim stays out of this file. Cargo applies [env] with force
# to rustc, build scripts and test children whatever target is chosen, so a job
# that switches to a target outside the cache would still carry a claim on it.
# Only the checkout identity is written: it is this worktree's own path, not a
# claim on the cache, and refresh needs it to recognise a moved worktree.
# Readers of the claim refuse by name when it is absent, and the cleaner judges
# processes by their own layout instead.
metadata = f'SECODE_WORKTREE_ROOT = {{ value = {quote(os.environ["SECODE_WORKTREE_ROOT"])}, force = true }}\n'
content = header + target + jobs + 'incremental = true\n' + flags + cache + metadata
# The test-scratch line is owned by value, not shape: expected is computed
# without the writable probe, so refresh can recognize our line even when
# the scratch is unavailable. The line is written only when the probe
# passes; force = false keeps a caller-provided TMPDIR in charge.
expected = str(tmp_scratch.base_path())
test_tmp_line = f'TMPDIR = {{ value = {quote(expected)}, force = false }}\n'
written = content + test_tmp_line if tmp_scratch.resolve_base() is not None else content
# Recognize exact prior generated files so refresh can remove their wrappers.
helpers = Path(sys.argv[3]).parent
if not (helpers/'rustc-cache.sh').is_file(): helpers = helpers/'build'
wrapper = str(helpers/'rustc-cache.sh')
sccache = shutil.which('sccache') or str(Path.home()/'.local/bin/sccache')
old_cache = cache + ''.join(f'{name} = {{ value = {quote(value)}, force = true }}\n'
    for name, value in [('SCCACHE_DIR', str(Path(os.environ['SECODE_CACHE_DIR'])/'sccache')),
                        ('SCCACHE_CACHE_SIZE', '100G'), ('SCCACHE_SERVER_PORT', '4226'),
                        ('SCCACHE_CLIENT_SIDE', '1')])
old = header + target + f'rustc-wrapper = {quote(wrapper)}\n' + jobs + 'incremental = false\n' + flags + old_cache
legacy = old.replace(quote(wrapper), quote(sccache), 1)
old += metadata + f'SECODE_SCCACHE = {{ value = {quote(sccache)}, force = true }}\n'
refresh = config.exists() and sys.argv[2] == '--refresh'
if (root / '.cargo/config').exists() or (config.exists() and not refresh):
    raise SystemExit('Cargo config already exists; preserve it and use scripts/shared-cargo.sh instead.')
if refresh:
    accepted = [content, old, legacy]
    accepted.append(content + test_tmp_line)
    for defaults in [content, old, legacy]:
        old = defaults.replace('# Local SE Code build defaults.', '# Local SE Code shared build defaults.', 1)
        accepted.append(old.replace(quote(os.environ['CARGO_TARGET_DIR']), quote(os.environ['SECODE_TARGET_ROOT']), 1))
    # A config written before the claim left [env] carries three keys where the
    # current file carries the one checkout identity. Build that older shape by
    # replacing the identity line, in the order the old script wrote them, so
    # refresh can replace it instead of refusing an existing worktree.
    claims = ''.join(f'{name} = {{ value = {quote(os.environ[name])}, force = true }}\n'
                     for name in ['SECODE_TARGET_ROOT', 'SECODE_WORKTREE_TARGET', 'SECODE_WORKTREE_ROOT']
                     if name in os.environ)
    if metadata and claims:
        for defaults in list(accepted):
            if metadata in defaults:
                accepted.append(defaults.replace(metadata, claims, 1))
    # Defaults installed before registry placement did not name these variables.
    accepted += ['\n'.join(line for line in defaults.split('\n')
                          if not line.startswith(('CARGO_HOME =', 'SECODE_CACHE_DIR =')))
                 for defaults in list(accepted)]
    accepted += [defaults.replace(f'jobs = {os.environ["CARGO_BUILD_JOBS"]}\n', f'jobs = {jobs}\n', 1)
                 for defaults in list(accepted) for jobs in (4, 8)]
    accepted += [defaults.replace('"100G"', '"20G"') for defaults in list(accepted)]
    accepted += ['\n'.join(line for line in defaults.split('\n') if not line.startswith('SCCACHE_SERVER_PORT ='))
                 for defaults in list(accepted)]
    accepted += ['\n'.join(line.replace('force = true', 'force = false')
                          if line.startswith('SCCACHE_') else line for line in defaults.split('\n'))
                 for defaults in list(accepted)]
    cargo_home = f'CARGO_HOME = {{ value = {quote(os.environ["CARGO_HOME"])}, force = false }}\n'
    accepted += [defaults.replace('[env]\n', '[env]\n' + cargo_home, 1) for defaults in list(accepted)]
    previous = config.read_text()
    # Our test-scratch line may stand anywhere in the file: when the whole
    # entry equals what we generate it is ours, and refresh rewrites the
    # canonical file (carrying the line only if the probe passes now). Any
    # other TMPDIR entry is a customization and refuses below.
    if test_tmp_line in previous:
        try:
            entry = tomllib.loads(previous)['env']['TMPDIR']
        except (KeyError, TypeError, AttributeError, ValueError):
            entry = None
        if (isinstance(entry, dict) and set(entry) == {'value', 'force'}
                and entry['value'] == expected and type(entry['force']) is bool
                and not entry['force']):
            previous = previous.replace(test_tmp_line, '', 1)
    if previous not in accepted:
        try:
            installed = tomllib.loads(previous)
            environment = installed['env']
            old_root = environment.get('SECODE_WORKTREE_ROOT', {}).get('value')
            # A config generated before the claim left [env] names the managed
            # root; one generated after it does not. Either way the worktree
            # target is the hash of the old checkout under that root.
            old_cache = ((environment.get('SECODE_TARGET_ROOT') or {}).get('value')
                         or os.environ['SECODE_TARGET_ROOT'])
            old_target = str(Path(old_cache) / 'worktrees' /
                             hashlib.sha256(old_root.encode()).hexdigest())
            if (isinstance(old_root, str) and Path(old_root).is_absolute() and
                    installed['build']['target-dir'] == old_target):
                previous = previous.replace(quote(old_root), quote(str(root)))
                previous = previous.replace(quote(old_target), quote(os.environ['SECODE_WORKTREE_TARGET']))
                previous = previous.replace(quote(str(Path(old_root) / 'scripts/build/rustc-cache.sh')),
                                            quote(wrapper))
        except (KeyError, TypeError, AttributeError, tomllib.TOMLDecodeError):
            pass
    if previous not in accepted:
        raise SystemExit('Existing Cargo config was customized; preserve it and use scripts/shared-cargo.sh instead.')
exclude = Path(subprocess.check_output(['git', 'rev-parse', '--git-path', 'info/exclude'], text=True).strip())
if not exclude.is_absolute(): exclude = root / exclude
exclude.parent.mkdir(parents=True, exist_ok=True)
existing = exclude.read_text() if exclude.exists() else ''
if '/.cargo/config.toml' not in existing.splitlines():
    with exclude.open('a') as handle: handle.write('\n/.cargo/config.toml\n')
config.parent.mkdir(parents=True, exist_ok=True)
if refresh:
    with tempfile.NamedTemporaryFile(mode='w', dir=config.parent, delete=False) as handle:
        temporary = Path(handle.name)
        handle.write(written)
    os.replace(temporary, config)
else:
    with config.open('x') as handle: handle.write(written)
print(f'Local Cargo defaults installed: {config}')
PY
