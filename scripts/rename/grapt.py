def bare_any(match: re.Match) -> str:
    text, start, end = match.string, match.start(), match.end()
    line_start = text.rfind("\n", 0, start) + 1
    line_end = text.find("\n", end)
    line = text[line_start:line_end if line_end >= 0 else len(text)]
    if HOST_PATH.search(text[max(line_start, start - 48):start]) or HOST_TAIL.match(text, end):
        KEPT["host path"] += 1
        return match.group(0)
    # A product namespace key (`secode/slash`) follows the rename on any line.
    if re.match(r"/[a-z]", text[end:end + 2]):
        return "grapt"
    if PROJECT_LINE.search(line):
        KEPT["project or campaign line"] += 1
        return match.group(0)
    return "grapt"


