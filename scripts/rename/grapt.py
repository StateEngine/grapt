#!/usr/bin/env python3
"""Rename the product from SE Code to Grapt over a working tree.

Idempotent and re-runnable over any branch: every rule matches only the old
spelling, so a second run changes nothing. It renames by an explicit allow-list:

- crate directories and package names `secode-*` -> `grapt-*`, Rust paths
  `secode_*` -> `grapt_*`, and binaries `secode*` -> `grapt*`, for exactly the
  workspace's own packages and binaries, read from their manifests;
- environment variables `SECODE_*` -> `GRAPT_*`, dot-directories `.secode*` ->
  `.grapt*`, and the display name `SE Code` -> `Grapt`;
- product config file names and schema ids `secode.<x>` -> `grapt.<x>`.

It never touches what StateEngine owns (its project id `secode`, the repository
and host paths, seat and floor names), third-party notices and licences, or
dated history. A bare `secode` is never replaced; every one left is reported.
Derived files are regenerated by their own tools afterwards: `--regenerate`
runs `cargo update --workspace --offline`, `cargo fmt --all` and the licence
generator.

Usage: python3 -I scripts/rename/grapt.py [--dry-run] [--regenerate] [--report FILE]
"""
