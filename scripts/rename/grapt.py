        ("bench-path", re.compile(r"(?<=/)secode(?=/)"), "grapt", "bench/"),
        # Bare `secode` inside snake_case identifiers: `no_secode_crate`.
        ("ident-mid", re.compile(r"(?<=[a-z0-9]_)secode(?=_|(?![A-Za-z0-9]))"), "grapt"),
        # Upper-case product forms: the config file name and test markers.
        ("upper-config", re.compile(r"(?<![A-Za-z0-9_])SECODE\.(?=(JSONC?|TOML)\b)"), "GRAPT."),
        ("upper-hyphen", re.compile(r"(?<![A-Za-z0-9_])SECODE-(?=[A-Z])"), "GRAPT-"),
        # A command line that runs the binary alone.
        ("bare-command-alone", re.compile(r"(?m)^([ \t]*(?:\$[ \t]+)?)secode[ \t]*$"), r"\1grapt"),
        # The display name.
        ("display", re.compile(r"\bSE Code\b"), "Grapt"),
        # PascalCase product names; StateEngine's exported prepare*/mint* API keeps its names.
        ("pascal", re.compile(r"(?<!prepare)(?<!mint)Secode(?![a-z])"), "Grapt"),
        # Every other bare `secode` is the product, except the StateEngine project
        # id and repository or host paths.
        ("bare-any", re.compile(r"(?:(?<![A-Za-z0-9_-])|(?<=\\n)|(?<=`n))secode(?![A-Za-z0-9_-])"), bare_any),
