# The box controller (scripts/build, remote-compute) addresses box state and
# operator contracts. Inside it the token decides, not its context: exactly the
# generated artifact tokens (workspace package, binary and target names, with
# their `.exe` and snake_case forms) rename, as whole tokens, wherever they
# appear; every other `secode` token stays. The two tokens that are also box
# names, the binary `secode` and the crate `secode-release`, are held unless
# their exact line is in the reviewed table scripts/rename/box-rename-table.json.
BOX_TREES = ("scripts/build/", "remote-compute/")
BOX_TOKEN_RE = re.compile(r"(?<![A-Za-z0-9_.-])secode(?:[A-Za-z0-9_.-]*[A-Za-z0-9])?(?![A-Za-z0-9_-])")
AMBIGUOUS = frozenset({"secode", "secode-release"})
BOX_TABLE = Path(__file__).with_name("box-rename-table.json")
GENERATED: set = set()
BOX_ALLOWED: set = set()


def generated_tokens(names) -> set:
    """Every artifact name, with its `.exe` and snake_case forms."""
    base = {name for name in names if name.startswith("secode")}
    return base | {name + ".exe" for name in base} | {name.replace("-", "_") for name in base}


def box_table(check: bool) -> set:
    """The reviewed (file, exact line) pairs where an ambiguous token is an
    artifact. A row whose exact text is no longer in its file fails before
    anything is written."""
    if not BOX_TABLE.is_file():
        return set()
    rows = json.loads(BOX_TABLE.read_text())
    allowed = set()
    for row in rows:
        if not row["file"].startswith(BOX_TREES):
            raise SystemExit(f"box rename table row outside the box controller: {row['file']}")
        # A row is its exact line text; the recorded number only locates it for
        # review, so an unrelated insertion above it does not make it stale.
        if check and row["text"] not in {line.strip() for line in (ROOT / row["file"]).read_text().splitlines()}:
            raise SystemExit(f"stale box rename table row: {row['file']}:{row['line']}")
        allowed.add((row["file"], row["text"]))
    return allowed


def box_rename(text: str, path: str, counts: Counter) -> str:
    def token(match: re.Match) -> str:
        name = match.group(0)
        if name not in GENERATED:
            return name
        if name in AMBIGUOUS:
            start = text.rfind("\n", 0, match.start()) + 1
            end = text.find("\n", match.end())
            line = text[start:end if end >= 0 else len(text)].strip()
            if (path, line) not in BOX_ALLOWED:
                return name
        counts["box-token"] += 1
        return "grapt" + name[len("secode"):]

    return BOX_TOKEN_RE.sub(token, text)


# Rules held back under a path until the box changes with them: the build and
# landing tooling reads the box operator's SECODE_* environment, which lives
# outside the repository.
HELD = {
    "env-prefix": ("scripts/build/",),
    "env-prefix-pattern": ("scripts/build/",),
}


def rename_text(text: str, table, counts: Counter, path: str = "") -> str:
    # Held names and marked lines are masked before any rule runs, so no later
    # rule can rename them, then restored unchanged.
    held = []

    def hold(match: re.Match) -> str:
        held.append(match.group(0))
        DENIED["keep marker" if "grapt-rename: keep" in match.group(0) else match.group(0)] += 1
        return f"\0{len(held) - 1}\0"

    if path.startswith(BOX_TREES):
        text = KEEP_LINE.sub(hold, text)
        text = box_rename(text, path, counts)
        return re.sub("\0([0-9]+)\0", lambda match: held[int(match.group(1))], text)
    text = PROTECTED.sub(hold, text)
    text = HELD_IDS.sub(hold, text)
    for rule in table:
        if rule[2] is None:
            text = rule[1].sub(hold, text)
    for rule in table:
        label, pattern, replacement = rule[:3]
        if replacement is None:
            continue
        scope = rule[3] if len(rule) > 3 else None
        if scope is not None and not path.startswith(scope):
            continue
        if path.startswith(HELD.get(label, ("\0",))):
            continue
        text, hits = pattern.subn(replacement, text)
        counts[label] += hits
    return re.sub("\0([0-9]+)\0", lambda match: held[int(match.group(1))], text)


