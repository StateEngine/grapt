BARE = r"(?<![A-Za-z0-9_./\\-])secode(?![A-Za-z0-9_-])"


def is_text(data: bytes) -> bool:
    return b"\0" not in data[:8192]


ENV_NAME = re.compile(r"SECODE_[A-Z0-9][A-Z0-9_]*")


def held_environment(files: list[str]) -> frozenset:
    """The SECODE_* names the box controller reads or writes."""
    names = set()
    for path in files:
        if path.startswith(BOX_TREES) and (ROOT / path).is_file():
            data = (ROOT / path).read_bytes()
            if is_text(data):
                names.update(ENV_NAME.findall(data.decode("utf-8", errors="replace")))
    return frozenset(names)


def held_files(files, read=None, artifacts=frozenset()) -> frozenset:
    """Names the box controller shares with the rest of the tree: its own files
    named after the product, and every other `secode-*` token it mentions that is
    not a renamed artifact (markers, stamps, archive and lock names), so that a
    producer and its box-side consumer keep one name."""
    names = {Path(path).stem for path in files if path.startswith(BOX_TREES) and "secode" in Path(path).name}
    if read is not None:
        for path in files:
            if path.startswith(BOX_TREES):
                text = read(path)
                if text:
                    names.update(token for token in BOX_TOKEN.findall(text)
                                 if token not in artifacts and token.removesuffix(".exe") not in artifacts)
    return frozenset(names)


BOX_TOKEN = re.compile(r"(?<![A-Za-z0-9_])secode-[A-Za-z0-9_.-]*[A-Za-z0-9]")


RESOLVE = r"""
import importlib, json, sys
from pathlib import Path
sys.path.insert(0, sys.argv[1])
out = {}
for name in ("heavy", "durable_jobs", "install_schedules"):
    module = importlib.import_module(name)
    for key, value in sorted(vars(module).items()):
        if key.isupper() and isinstance(value, (str, Path, tuple, int)):
            out[name + "." + key] = repr(value)
schedules = importlib.import_module("install_schedules")
home = Path("/home/example")
out["retention_units"] = repr(sorted(schedules.retention_units(home).items()))
out["units"] = repr(sorted(schedules.units(Path("/srv/clone"), home, "agt-abc-example").items()))
print(json.dumps(out, sort_keys=True))
"""


def resolution(directory: Path) -> dict:
    """What the box controller resolves: its paths, locks, units and refs."""
    result = subprocess.run([sys.executable, "-I", "-c", RESOLVE, str(directory)], capture_output=True,
                            text=True, timeout=60, env={"HOME": "/home/example", "PATH": "/usr/bin:/bin"})
    if result.returncode != 0:
        raise SystemExit(f"box resolution failed for {directory}: {result.stderr.strip()[-400:]}")
    return json.loads(result.stdout)


def mapper_for(ref: str):
    """The rename as a text function, with names read from `ref`'s manifests,
    so a tool can ask whether a changed line is exactly the rename of an old one."""
    listing = subprocess.run(["git", "ls-tree", "-d", "--name-only", f"{ref}:crates"], cwd=ROOT,
                             capture_output=True, text=True).stdout.split()
    packages, binaries = set(), set()
    for directory in listing:
        shown = subprocess.run(["git", "show", f"{ref}:crates/{directory}/Cargo.toml"], cwd=ROOT,
                               capture_output=True, text=True)
        if shown.returncode != 0:
            continue
        document = tomllib.loads(shown.stdout)
        name = document.get("package", {}).get("name", "")
        if name.startswith("secode"):
            packages.add(name)
            binaries.add(name)
        for binary in document.get("bin", []):
            if binary.get("name", "").startswith("secode"):
                binaries.add(binary["name"])
    held = subprocess.run(["git", "grep", "-h", "-o", "-E", ENV_NAME.pattern, ref, "--", *BOX_TREES],
                          cwd=ROOT, capture_output=True, text=True).stdout.split()
    box_files = subprocess.run(["git", "ls-tree", "-r", "--name-only", ref, "--", *BOX_TREES],
                               cwd=ROOT, capture_output=True, text=True).stdout.split()
    def read_text(path):
        shown = subprocess.run(["git", "show", f"{ref}:{path}"], cwd=ROOT, capture_output=True)
        return shown.stdout.decode("utf-8", errors="replace") if shown.returncode == 0 and is_text(shown.stdout) else ""

    GENERATED.clear()
    GENERATED.update(generated_tokens(packages | binaries))
    BOX_ALLOWED.clear()
    BOX_ALLOWED.update(box_table(check=False))
    table = rules(sorted(packages), sorted(binaries), frozenset(held),
                  held_files(box_files, read_text, frozenset(GENERATED)))
    return lambda text, path="": rename_text(text, table, Counter(), path)


RUSTFMT = ["rustup", "run", "1.97.1", "rustfmt", "--emit", "stdout", "--edition", "2021",
           "--style-edition", "2021", "--config", "newline_style=Unix,skip_children=true",
           "--color", "never"]
INCLUDE = re.compile(r'(?m)^( *)include!\("([^"]+)"\)')


def format_fragments() -> None:
    """Format `include!` fragments, which cargo fmt cannot see, exactly as the
    direct-include law checks them: in place, at their site's indentation."""
    for carrier in sorted((ROOT / "crates").rglob("*.rs")):
        try:
            text = carrier.read_text()
        except (OSError, UnicodeDecodeError):
            continue
        for indent, target in INCLUDE.findall(text):
            fragment = (carrier.parent / target).resolve()
            if not fragment.is_file() or len(indent) not in (0, 4):
                continue
            source = fragment.read_text()
            wrapped = source if not indent else "mod __grapt_fragment {\n" + source + "}\n"
            result = subprocess.run(RUSTFMT, input=wrapped, text=True, capture_output=True)
            if result.returncode != 0:
                raise SystemExit(f"rustfmt refused {fragment}: {result.stderr.strip()}")
            formatted = result.stdout
            if indent:
                lines = formatted.splitlines(keepends=True)
                if not lines or not lines[0].startswith("mod __grapt_fragment") or lines[-1] != "}\n":
                    raise SystemExit(f"fragment wrapper lost for {fragment}")
                formatted = "".join(lines[1:-1])
            if formatted != source:
                fragment.write_text(formatted)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true", help="count, change nothing")
    parser.add_argument("--regenerate", action="store_true", help="run the derived-file generators")
    parser.add_argument("--report", type=Path, help="write a JSON report here")
    args = parser.parse_args()

    packages, binaries = workspace_names()
    files = tracked()
    metadata = subprocess.run(["cargo", "metadata", "--format-version", "1", "--no-deps", "--offline"],
                              cwd=ROOT, capture_output=True, text=True, check=True)
    names = set()
    for package in json.loads(metadata.stdout)["packages"]:
        names.add(package["name"])
        names.update(target["name"] for target in package["targets"])
    GENERATED.clear()
    GENERATED.update(generated_tokens(names))
    BOX_ALLOWED.clear()
    # On a tree already renamed nothing is generated, and the rows are applied.
    BOX_ALLOWED.update(box_table(check=bool(GENERATED)))
    held_env = held_environment(files)
    def read_text(path):
        data = (ROOT / path).read_bytes() if (ROOT / path).is_file() else b""
        return data.decode("utf-8", errors="replace") if is_text(data) else ""

    table = rules(packages, binaries, held_env, held_files(files, read_text, frozenset(GENERATED)))
    # The box controller as it was, for the resolution check after the rename.
    original_box = Path(tempfile.mkdtemp(prefix="grapt-rename-box-"))
    shutil.copytree(ROOT / "scripts/build", original_box / "build")
    content_counts, path_counts = Counter(), Counter()
    edited, moves = [], []

    # Contents first, at their current paths.
    for path in files:
        if excluded(path):
            continue
        file = ROOT / path
        if not file.is_file() or file.is_symlink():
            continue
        data = file.read_bytes()
        if not is_text(data):
            continue
        try:
            text = data.decode("utf-8")
        except UnicodeDecodeError:
            continue
        renamed = rename_text(text, table, content_counts, path)
        if renamed != text:
            edited.append(path)
            if not args.dry_run:
                file.write_bytes(renamed.encode("utf-8"))

    # Then paths: whole crate directories, then any other tracked path.
    for path in files:
        if excluded(path):
            continue
        new = rename_text(path, table, path_counts, path)
        if new != path:
            moves.append((path, new))
    if not args.dry_run:
        crate_dirs = sorted({(m[0].split("/")[1], m[1].split("/")[1]) for m in moves if m[0].startswith("crates/") and m[0].split("/")[1] != m[1].split("/")[1]})
        for old, new in crate_dirs:
            if (ROOT / "crates" / old).exists() and not (ROOT / "crates" / new).exists():
                subprocess.run(["git", "mv", f"crates/{old}", f"crates/{new}"], cwd=ROOT, check=True)
        for old, new in moves:
            current = old
            for o, n in crate_dirs:
                if current.startswith(f"crates/{o}/"):
                    current = f"crates/{n}/" + current[len(f"crates/{o}/"):]
            if current != new and (ROOT / current).exists():
                (ROOT / new).parent.mkdir(parents=True, exist_ok=True)
                subprocess.run(["git", "mv", current, new], cwd=ROOT, check=True)

    if not args.dry_run:
        before, after = resolution(original_box / "build"), resolution(ROOT / "scripts/build")
        changed = sorted(key for key in before.keys() | after.keys() if before.get(key) != after.get(key))
        if changed:
            print("box controller resolution changed: " + ", ".join(changed), file=sys.stderr)
            return 3
    shutil.rmtree(original_box, ignore_errors=True)

    if args.regenerate and not args.dry_run:
        subprocess.run(["cargo", "update", "--workspace", "--offline"], cwd=ROOT, check=True)
        # Shorter names change line lengths; the formatter re-wraps them.
        subprocess.run(["cargo", "fmt", "--all"], cwd=ROOT, check=True)
        format_fragments()
        subprocess.run([sys.executable, "-B", "scripts/release/licenses.py", "generate"], cwd=ROOT, check=True)

    leftovers = Counter()
    bare = re.compile(r"[A-Za-z0-9_./\\-]*(secode|SECODE|Secode|SE_CODE)[A-Za-z0-9_-]*")
    spellings = {"SECODE": set(), "GRAPT": set()}
    renamed_holds = []
    schema_ids = {"secode": {}, "grapt": {}}
    for path in tracked() if not args.dry_run else files:
        file = ROOT / path
        if not file.is_file():
            continue
        data = file.read_bytes()
        if not is_text(data):
            continue
        text = data.decode("utf-8", errors="replace")
        if args.dry_run and not excluded(path):
            text = rename_text(text, table, Counter(), path)
        # Excluded files still produce and consume schema ids, so they count here.
        if not path.startswith("scripts/rename/") and not (path.startswith("docs/") and "/receipts/" in path):
            for prefix, name in SCHEMA_ID.findall(text):
                schema_ids[prefix].setdefault(name, path)
        if excluded(path):
            continue
        for match in bare.finditer(text):
            leftovers[match.group(0)] += 1
        if not path.startswith("scripts/rename/"):
            renamed_holds += [f"{path}: {match.group(0)}" for match in RENAMED_HOLDS.finditer(text)]
            renamed_holds += [f"{path}: {match.group(0)}" for match in RENAMED_HELD_IDS.finditer(text)]
        for prefix, name in re.findall(r"(?<![A-Za-z0-9_])(SECODE|GRAPT)_([A-Z0-9][A-Z0-9_]*)", text):
            spellings[prefix].add(name)

    report = {
        "packages": packages,
        "binaries": binaries,
        "files_edited": len(edited),
        "paths_moved": len(moves),
        "content_hits": dict(content_counts),
        "path_hits": dict(path_counts),
        "deny_list_hits": dict(DENIED.most_common()),
        "held_environment": sorted(held_env),
        "bare_kept": dict(KEPT.most_common()),
        "leftover_tokens": dict(leftovers.most_common()),
    }
    if args.report:
        args.report.write_text(json.dumps(report, indent=1) + "\n")
    print(json.dumps({k: v for k, v in report.items() if k != "leftover_tokens"}, indent=1))
    print(f"leftover distinct tokens: {len(leftovers)}, occurrences: {sum(leftovers.values())}")
    # A variable spelled both ways would split its producers from its consumers.
    split = sorted((spellings["SECODE"] & spellings["GRAPT"]) - DUAL_ENVIRONMENT)
    if split:
        print("split environment contracts: " + ", ".join(split), file=sys.stderr)
        return 2
    if renamed_holds:
        print("split durable formats: " + ", ".join(renamed_holds), file=sys.stderr)
        return 2
    split_ids = sorted(schema_ids["secode"].keys() & schema_ids["grapt"].keys())
    if split_ids:
        print("split schema ids: " + ", ".join(
            f"{name} (secode in {schema_ids['secode'][name]}, grapt in {schema_ids['grapt'][name]})"
            for name in split_ids), file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
