# Paths the rename never edits: third-party attribution and licences, the
# StateEngine component, the licence register (regenerated), and dated history.
EXCLUDED_PREFIXES = (
    "notices/",
    "licenses/",
    "third-party/",
    "packages/stateengine/",
    "scripts/rename/",
)
DATED = re.compile(r"(19|20)\d{2}-?[01]\d-?[0-3]\d|(19|20)\d{2}-[01]\d(?![0-9])")
DATED_DIRS = ("/receipts/",)


def tracked() -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "-z"], cwd=ROOT, check=True, capture_output=True
    ).stdout
    return [path for path in out.decode().split("\0") if path]


# Root licence files carry the copyright attribution, which the rename never changes.
EXCLUDED_FILES = ("LICENSE-MIT", "LICENSE-APACHE")
# Compatibility code and fixtures written after the rename that name the old
# spellings on purpose (the legacy package inventory and its aliases); a branch
# re-run never carries them.
