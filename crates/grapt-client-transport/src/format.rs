//! Numeric labels shared by TUI status, accounting and transcript presenters.
/// Shared TUI counter spelling: one decimal for thousands and millions.
pub fn count(value: u64) -> String {
    if value >= 1_000_000 {
        format!("{:.1}M", value as f64 / 1_000_000.0)
    } else if value >= 1_000 {
        format!("{:.1}k", value as f64 / 1_000.0)
    } else {
        value.to_string()
    }
}
